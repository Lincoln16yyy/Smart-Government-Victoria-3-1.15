"""Render the research section of the shared journal widget and its language files."""
from pathlib import Path

from research_policy import CONTEXTS, POLICY

SLOTS = (1, 2, 3)
ROOT_COUNTRY = "GuiScope.SetRoot(JournalEntry.GetCountry.MakeScope).End"


def textbox(key: str, selector: str | None = None, size: str = "small") -> str:
    visibility = (
        f"\n\t\t\tvisible = \"[GetScriptedGui('sg_research_{selector}_sgui').IsShown({ROOT_COUNTRY})]\""
        if selector else ""
    )
    return f"""
		textbox = {{{visibility}
			autoresize = yes
			multiline = yes
			align = left|nobaseline
			using = fontsize_{size}
			minimumsize = {{ 484 -1 }}
			maximumsize = {{ 484 -1 }}
			text = "{key}"
		}}"""


def section() -> str:
    rows = "".join(
        textbox(f"sg_research_card_{slot}_{token}", f"{slot}_{token}")
        for slot in SLOTS
        for name, *_ in POLICY
        for token in (name.replace("-", "_"),)
    )
    return f"""
	flowcontainer = {{
		visible = "[GetScriptedGui('sg_research_visible_sgui').IsShown({ROOT_COUNTRY})]"
		direction = vertical
		spacing = 5
		ignoreinvisible = yes

		widget = {{
			size = {{ 500 36 }}
			background = {{ using = dark_area }}
			textbox = {{
				position = {{ 8 0 }}
				parentanchor = vcenter
				autoresize = yes
				using = fontsize_medium
				text = "sg_research_title"
			}}
			button_icon_round_action = {{
				position = {{ -6 0 }}
				parentanchor = right|vcenter
				size = {{ 32 32 }}
				blockoverride "icon" {{
					texture = "gfx/interface/buttons/button_icons/reset.dds"
				}}
				using = select_button_sound
				using = tooltip_se
				tooltip = "sg_research_refresh_tt"
				enabled = "[GetScriptedGui('sg_research_refresh_sgui').IsValid({ROOT_COUNTRY})]"
				onclick = "[GetScriptedGui('sg_research_refresh_sgui').Execute({ROOT_COUNTRY})]"
			}}
		}}
{textbox("sg_research_active", "active")}
{textbox("sg_research_empty", "empty")}
{rows}
	}}"""


def write_localizations(out: Path, records: list[dict]) -> None:
    policy = {row[0]: row[1:] for row in POLICY}
    languages = {
        "braz_por": {
            "title": "Conselheiro Tecnológico",
            "refresh_tt": "Reavaliar prioridades de pesquisa",
            "active": "Há uma pesquisa em curso. Use as sugestões para planejar o próximo passo.",
            "empty": "Nenhuma tecnologia disponível dentre as prioridades identificadas.",
            "labels": ("Prioridade 1", "A seguir · Prioridade 2", "Alternativa · Prioridade 3"),
            "categories": {"production": "Produção", "military": "Militar", "society": "Sociedade"},
            "instructions": "Tecnologia → {category} → {name}. Pré-requisitos atendidos.",
            "progress": "Progresso",
        },
        "english": {
            "title": "Technology Advisor",
            "refresh_tt": "Reassess research priorities",
            "active": "Research is in progress. Use these suggestions to plan the next step.",
            "empty": "No available technology matches the identified priorities.",
            "labels": ("Priority 1", "Next · Priority 2", "Alternative · Priority 3"),
            "categories": {"production": "Production", "military": "Military", "society": "Society"},
            "instructions": "Technology → {category} → {name}. Prerequisites met.",
            "progress": "Progress",
        },
    }
    for index, (language, words) in enumerate(languages.items()):
        lines = [f"l_{language}:", " # Generated by tools/build_research_data.py."]
        for key in ("title", "refresh_tt", "active", "empty"):
            lines.append(f' sg_research_{key}:0 "{words[key]}"')
        for record in records:
            tech = record["name"]
            token = tech.replace("-", "_")
            context, _, *benefits = policy[tech]
            expr = f"GetTechnology('{tech}')"
            name = f"[{expr}.GetNameNoFormatting]"
            category = words["categories"][record["category"]]
            path = words["instructions"].format(category=category, name=name)
            progress = (
                f"{words['progress']} [{expr}.GetProgress(GetPlayer.Self)|0] / "
                f"[{expr}.GetCost(GetPlayer.Self)|0]"
            )
            for slot in SLOTS:
                title = f"#bold {words['labels'][slot - 1]} · {name}#!"
                body = "\\n".join((title, CONTEXTS[context][index], benefits[index], path, progress))
                lines.append(f' sg_research_card_{slot}_{token}:0 "{body}"')
        path = out / f"localization/{language}/sg_research_l_{language}.yml"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(lines) + "\n", encoding="utf-8-sig")
