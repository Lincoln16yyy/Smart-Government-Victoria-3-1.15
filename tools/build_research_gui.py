def main() -> int:
    if not DATA.is_file():
        raise SystemExit(
            f"Missing {DATA}. Run tools/build_research_data.py before "
            "tools/build_research_gui.py."
        )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8-sig")
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
